"""Alembic environment. The database URL comes from app settings unless a caller overrides it."""

from logging.config import fileConfig

from alembic import context
from sqlalchemy import create_engine, pool

from app.core.config import get_settings

config = context.config
if config.config_file_name is not None:
    # Keep the application's own loggers alive when migrations run inside another process.
    fileConfig(config.config_file_name, disable_existing_loggers=False)

if context.is_offline_mode():
    raise SystemExit("Offline migrations are not supported; run against a live database.")

url = config.get_main_option("sqlalchemy.url") or get_settings().database_url
engine = create_engine(url, poolclass=pool.NullPool)

with engine.connect() as connection:
    # target_metadata is None on purpose: migrations are hand-written SQL, not autogenerated.
    context.configure(connection=connection, target_metadata=None, transaction_per_migration=True)
    with context.begin_transaction():
        context.run_migrations()

engine.dispose()